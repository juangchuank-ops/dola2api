void i18n.use(initReactI18next).init({
  resources: {
    "zh-CN": { translation: zhCN },
    en: { translation: en },
  },
  lng: readInitialLanguage(),
  fallbackLng: "zh-CN",
  interpolation: { escapeValue: false },
  returnNull: false,
});

function readInitialLanguage(): string {
  try {
    const stored = window.localStorage.getItem("dola2api:language");
    if (stored === "zh-CN" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  return "zh-CN";
}

i18n.on("languageChanged", (language) => {
  try {
    window.localStorage.setItem("dola2api:language", language);
  } catch {
    /* ignore */
  }
});

export default i18n;
